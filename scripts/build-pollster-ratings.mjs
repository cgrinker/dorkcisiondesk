/**
 * Convert Silver Bulletin's pollster ratings workbook into a D1 seed file.
 *
 * Input:  data/pollster-stats-2026.xlsx  (from natesilver.net/p/pollster-ratings-silver-bulletin,
 *         free to use with attribution to Silver Bulletin)
 * Output: data/pollster-ratings.sql
 *
 * Mapping:
 *   quality      = clamp(0.7 - 0.3 * PredictivePlusMinus, 0.05, 1.0)
 *                  (PPM is negative-is-better, roughly -1.5 .. +2; an unknown
 *                   pollster's default 0.5 corresponds to PPM ~ +0.67)
 *   house_effect = "House Effect" column (mean-reverted; positive = leans Dem,
 *                  matching rawpolls' bias = pollMargin - actualMargin with
 *                  margin = Dem - Rep)
 *   banned       = "Banned by Silver Bulletin" == yes
 *
 * Run: node scripts/build-pollster-ratings.mjs
 */

import XLSX from "xlsx";
import { writeFileSync } from "node:fs";

const wb = XLSX.readFile("data/pollster-stats-2026.xlsx");
const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { header: 1 });

const header = rows[0];
const col = (name) => {
  const i = header.findIndex((h) => typeof h === "string" && h.replace(/\s+/g, " ").trim().startsWith(name));
  if (i < 0) throw new Error(`column not found: ${name}`);
  return i;
};

const cName = col("Pollster") === 0 ? 1 : col("Pollster"); // col 0 is a rank index
const cPpm = col("Predictive");
const cGrade = col("SB Grade");
const cHouse = col("House Effect");
const cBanned = col("Banned");
const cNPolls = col("# of Polls");

const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x));
const esc = (s) => String(s).replace(/'/g, "''");

const stmts = [];
let banned = 0;
for (const row of rows.slice(1)) {
  const name = row[cName];
  if (!name || typeof name !== "string") continue;
  const ppm = typeof row[cPpm] === "number" ? row[cPpm] : 0.67;
  const quality = clamp(0.7 - 0.3 * ppm, 0.05, 1.0);
  const house = typeof row[cHouse] === "number" ? row[cHouse] : 0;
  const isBanned = String(row[cBanned]).toLowerCase() === "yes" ? 1 : 0;
  banned += isBanned;

  stmts.push(
    `INSERT INTO pollsters (name, quality, house_effect, banned) VALUES ('${esc(name)}', ${quality.toFixed(4)}, ${house.toFixed(4)}, ${isBanned})\n` +
      `  ON CONFLICT(name) DO UPDATE SET quality = excluded.quality, house_effect = excluded.house_effect, banned = excluded.banned;`,
  );
}

const out =
  `-- Generated by scripts/build-pollster-ratings.mjs — do not edit.\n` +
  `-- Source: Silver Bulletin pollster ratings (Jan 2026), used with attribution.\n` +
  `-- https://www.natesilver.net/p/pollster-ratings-silver-bulletin\n\n` +
  stmts.join("\n") +
  "\n";

writeFileSync("data/pollster-ratings.sql", out);
console.log(`wrote data/pollster-ratings.sql: ${stmts.length} pollsters (${banned} banned)`);
console.log(`sample grades check — rows with PPM/quality:`);
for (const row of rows.slice(1, 6)) {
  console.log(`  ${row[cName]} (${row[cGrade]}, ${row[cNPolls]} polls): ppm=${row[cPpm]?.toFixed?.(2)} -> quality=${clamp(0.7 - 0.3 * (row[cPpm] ?? 0.67), 0.05, 1).toFixed(2)}, house=${row[cHouse]?.toFixed?.(2)}`);
}
