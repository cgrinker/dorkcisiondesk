/**
 * Candidate-history seed: for every senate/governor race whose incumbent is
 * running again, find that person's most recent actual margin in the same
 * race from the rawpolls archive (Silver Bulletin, results attached) and
 * emit UPDATE statements. Also computes the persistence coefficient k —
 * "how much of a repeat candidate's last margin shows up next time" — from
 * every repeat-candidate pair in the archive (through-origin slope).
 *
 * Matching rule (conservative): history applies only when the archive
 * winner's surname matches a CURRENT candidate of the incumbent party in
 * our candidates table — i.e., the same person is actually running. Open
 * seats and new matchups get no history.
 *
 * Run: node scripts/build-incumbent-history.mjs [api-base]
 * Output: data/incumbent-history.sql
 */

import XLSX from "xlsx";
import { writeFileSync } from "node:fs";

const API = process.argv[2] ?? "https://elections.cgrinker.workers.dev";

const rows = XLSX.utils.sheet_to_json(XLSX.readFile("data/rawpolls.xlsx").Sheets["Rawpolls 040626"]);
const races = new Map();
for (const r of rows) {
  if (r.type_simple !== "Sen-G" && r.type_simple !== "Gov-G") continue;
  if (typeof r.margin_actual !== "number") continue;
  let flip;
  if (r.cand1_party === "DEM" && r.cand2_party === "REP") flip = 1;
  else if (r.cand1_party === "REP" && r.cand2_party === "DEM") flip = -1;
  else continue;
  const key = `${r.location}|${r.type_simple}|${r.year}`;
  if (!races.has(key)) {
    races.set(key, {
      loc: r.location, type: r.type_simple, year: r.year,
      demMargin: flip * r.margin_actual,
      dem: String(flip === 1 ? r.cand1_name : r.cand2_name || "").toLowerCase(),
      rep: String(flip === 1 ? r.cand2_name : r.cand1_name || "").toLowerCase(),
    });
  }
}
const hist = [...races.values()];
const surname = (n) => n.trim().split(/\s+/).pop() ?? "";

// Persistence coefficient from all repeat-candidate pairs.
let sxy = 0, sxx = 0, nPairs = 0;
for (const a of hist) for (const b of hist) {
  if (a.loc !== b.loc || a.type !== b.type) continue;
  const gap = b.year - a.year;
  if (gap < 2 || gap > 6) continue;
  const aNames = [surname(a.dem), surname(a.rep)].filter((s) => s.length > 3);
  const bNames = [surname(b.dem), surname(b.rep)];
  if (aNames.filter((s) => bNames.includes(s)).length !== 1) continue;
  sxy += a.demMargin * b.demMargin; sxx += a.demMargin ** 2; nPairs++;
}
console.log(`persistence k = ${(sxy / sxx).toFixed(3)} from ${nPairs} repeat-candidate pairs`);

// Our races + candidates.
const out = [
  "-- Generated by scripts/build-incumbent-history.mjs — do not edit.",
  "-- Incumbent's last Dem-minus-Rep margin where the same person runs again.",
  "-- Source: Silver Bulletin rawpolls archive (results attached).",
  "",
];
for (const type of ["senate", "governor"]) {
  const list = await (await fetch(`${API}/races?type=${type}&limit=100`)).json();
  for (const r of list) {
    if (r.incumbent_party !== "D" && r.incumbent_party !== "R") continue;
    const archType = type === "senate" ? "Sen-G" : "Gov-G";
    const prior = hist
      .filter((h) => h.loc === r.state && h.type === archType && h.year >= 2018 && h.year <= 2024)
      .sort((a, b) => b.year - a.year)[0];
    if (!prior) continue;
    const winnerName = prior.demMargin > 0 ? prior.dem : prior.rep;
    const winnerParty = prior.demMargin > 0 ? "D" : "R";
    if (winnerParty !== r.incumbent_party) continue;

    const detail = await (await fetch(`${API}/races/${r.race_id}`)).json();
    const running = detail.candidates.some(
      (c) =>
        c.party === winnerParty &&
        c.name.toLowerCase().includes(surname(winnerName)),
    );
    if (!running) continue;

    out.push(
      `UPDATE races SET incumbent_last_margin = ${prior.demMargin.toFixed(1)} WHERE id = '${r.race_id}'; -- ${winnerName} ${prior.year}`,
    );
  }
}
writeFileSync("data/incumbent-history.sql", out.join("\n") + "\n");
console.log(`wrote data/incumbent-history.sql: ${out.length - 4} races with running incumbents`);
