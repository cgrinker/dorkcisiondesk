/**
 * Build the House district seed from The Downballot's 2024 presidential
 * results calculated on the 2026 congressional maps (includes all states
 * that redistricted mid-decade). Free data; attribution: The Downballot.
 *   https://www.the-downballot.com/p/the-downballots-calculations-of-presidential
 *
 * Input:  data/downballot-presbycd-2026maps.csv  (raw Harris/Trump votes per district)
 * Output: data/seed-house.sql  (435 races + incumbent candidates)
 *
 * Validation before anything is emitted:
 *   - exactly 435 districts, no duplicates, every state accounted for
 *   - national vote totals reconcile with certified 2024 results (±1%)
 *   - spot-check statewide margins (TX/CA/NY/FL) against certified numbers
 * A failure aborts the build — we never seed unreconciled leans.
 *
 * lean = district two-way margin − national two-way margin (Dem points).
 *
 * Run: node scripts/build-district-leans.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";

// Certified 2024 national totals (FEC official results).
const CERT_HARRIS = 75_017_613;
const CERT_TRUMP = 77_303_568;
// Certified statewide two-way margins (Dem − Rep, pts) for spot checks.
const CERT_STATE_MARGINS = { TX: -13.9, CA: 20.9, NY: 13.0, FL: -13.4 };

const REGION = {
  CT: "northeast", DE: "northeast", MA: "northeast", MD: "northeast", ME: "northeast",
  NH: "northeast", NJ: "northeast", NY: "northeast", PA: "northeast", RI: "northeast", VT: "northeast",
  AL: "south", AR: "south", FL: "south", GA: "south", KY: "south", LA: "south", MS: "south",
  NC: "south", OK: "south", SC: "south", TN: "south", TX: "south", VA: "south", WV: "south",
  IA: "midwest", IL: "midwest", IN: "midwest", KS: "midwest", MI: "midwest", MN: "midwest",
  MO: "midwest", ND: "midwest", NE: "midwest", OH: "midwest", SD: "midwest", WI: "midwest",
  AK: "west", AZ: "west", CA: "west", CO: "west", HI: "west", ID: "west", MT: "west",
  NM: "west", NV: "west", OR: "west", UT: "west", WA: "west", WY: "west",
};

const lines = readFileSync("data/downballot-presbycd-2026maps.csv", "utf8").split(/\r?\n/);
const num = (s) => parseFloat(String(s).replace(/[",]/g, ""));
const esc = (s) => String(s).replace(/'/g, "''");

// Quote-aware CSV split.
function cells(line) {
  const out = [];
  let cur = "";
  let q = false;
  for (const ch of line) {
    if (q) {
      if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { out.push(cur); cur = ""; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const districts = [];
for (const line of lines) {
  const c = cells(line);
  const m = /^([A-Z]{2})-(\d{2}|AL)$/.exec(c[0] ?? "");
  if (!m) continue;
  const harris = num(c[4]);
  const trump = num(c[5]);
  if (!Number.isFinite(harris) || !Number.isFinite(trump)) {
    throw new Error(`bad vote counts for ${c[0]}: ${c[4]} / ${c[5]}`);
  }
  districts.push({
    state: m[1],
    district: m[2] === "AL" ? 1 : parseInt(m[2]),
    incumbent: (c[1] ?? "").trim(),
    party: /\(D\)/.test(c[2]) ? "D" : /\(R\)/.test(c[2]) ? "R" : "open",
    harris,
    trump,
  });
}

// ---- Validation ----
if (districts.length !== 435) throw new Error(`expected 435 districts, got ${districts.length}`);
const ids = new Set(districts.map((d) => `${d.state}-${d.district}`));
if (ids.size !== 435) throw new Error("duplicate district ids");

const totHarris = districts.reduce((s, d) => s + d.harris, 0);
const totTrump = districts.reduce((s, d) => s + d.trump, 0);
for (const [label, got, cert] of [["Harris", totHarris, CERT_HARRIS], ["Trump", totTrump, CERT_TRUMP]]) {
  const err = Math.abs(got - cert) / cert;
  if (err > 0.01) throw new Error(`${label} national total off by ${(err * 100).toFixed(2)}% (${got} vs certified ${cert})`);
  console.log(`reconciled ${label}: ${got.toLocaleString()} vs certified ${cert.toLocaleString()} (${(err * 100).toFixed(3)}% off)`);
}

for (const [state, certMargin] of Object.entries(CERT_STATE_MARGINS)) {
  const rows = districts.filter((d) => d.state === state);
  const h = rows.reduce((s, d) => s + d.harris, 0);
  const t = rows.reduce((s, d) => s + d.trump, 0);
  const margin = ((h - t) / (h + t)) * 100;
  if (Math.abs(margin - certMargin) > 1.0) {
    throw new Error(`${state} margin ${margin.toFixed(1)} vs certified ${certMargin} — boundary aggregation looks wrong`);
  }
  console.log(`spot-check ${state}: D${margin >= 0 ? "+" : ""}${margin.toFixed(1)} (certified ${certMargin >= 0 ? "D+" + certMargin : "R+" + -certMargin})`);
}

const natMargin = ((totHarris - totTrump) / (totHarris + totTrump)) * 100;
console.log(`national two-way margin: ${natMargin.toFixed(2)}`);

// ---- Emit ----
const out = [
  "-- Generated by scripts/build-district-leans.mjs — do not edit.",
  "-- 2024 presidential results by 2026 congressional district: The Downballot",
  "-- (the-downballot.com), used with attribution. lean = district two-way",
  `-- margin minus national two-way margin (${natMargin.toFixed(2)}).`,
  "",
];
for (const d of districts.sort((a, b) => a.state.localeCompare(b.state) || a.district - b.district)) {
  const margin = ((d.harris - d.trump) / (d.harris + d.trump)) * 100;
  const lean = margin - natMargin;
  const id = `house-2026-${d.state}-${String(d.district).padStart(2, "0")}`;
  out.push(
    `INSERT OR IGNORE INTO races (id, cycle, type, state, district, partisan_lean, incumbent_party, region) VALUES ` +
      `('${id}', 2026, 'house', '${d.state}', ${d.district}, ${lean.toFixed(1)}, '${d.party}', '${REGION[d.state]}');`,
  );
  if (d.incumbent && d.party !== "open") {
    out.push(
      `INSERT OR IGNORE INTO candidates (race_id, name, party, incumbent) VALUES ` +
        `('${id}', '${esc(d.incumbent)}', '${d.party}', 1);`,
    );
  }
}
writeFileSync("data/seed-house.sql", out.join("\n") + "\n");
console.log(`wrote data/seed-house.sql: ${districts.length} districts`);
