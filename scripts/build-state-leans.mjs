/**
 * Compute state partisan leans for Senate/Governor races from The
 * Downballot's district-level 2024 results (district boundaries are
 * irrelevant to state sums), replacing the original hand-written seed
 * estimates. Same validation discipline as the House pipeline: national
 * totals must reconcile with certified results before anything is emitted.
 *
 * lean = state two-way margin − national two-way margin, where "national"
 * is the sum of all 435 districts (excludes DC, which has no district —
 * a ~0.2 pt consistent offset shared with the House leans, kept for
 * internal consistency).
 *
 * Run: node scripts/build-state-leans.mjs [api-base]
 * Output: data/seed-state-leans.sql (+ a printed old-vs-new diff report)
 */

import { readFileSync, writeFileSync } from "node:fs";

const API = process.argv[2] ?? "https://elections.cgrinker.workers.dev";
const CERT_HARRIS = 75_017_613;
const CERT_TRUMP = 77_303_568;

const lines = readFileSync("data/downballot-presbycd-2026maps.csv", "utf8").split(/\r?\n/);
const num = (s) => parseFloat(String(s).replace(/[",]/g, ""));

function cells(line) {
  const out = [];
  let cur = "";
  let q = false;
  for (const ch of line) {
    if (q) { if (ch === '"') q = false; else cur += ch; }
    else if (ch === '"') q = true;
    else if (ch === ",") { out.push(cur); cur = ""; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const states = new Map(); // abbr -> {harris, trump}
let n = 0;
for (const line of lines) {
  const c = cells(line);
  const m = /^([A-Z]{2})-(\d{2}|AL)$/.exec(c[0] ?? "");
  if (!m) continue;
  const harris = num(c[4]);
  const trump = num(c[5]);
  if (!Number.isFinite(harris) || !Number.isFinite(trump)) throw new Error(`bad row ${c[0]}`);
  const s = states.get(m[1]) ?? { harris: 0, trump: 0 };
  s.harris += harris;
  s.trump += trump;
  states.set(m[1], s);
  n++;
}
if (n !== 435) throw new Error(`expected 435 districts, got ${n}`);

const totH = [...states.values()].reduce((a, s) => a + s.harris, 0);
const totT = [...states.values()].reduce((a, s) => a + s.trump, 0);
for (const [label, got, cert] of [["Harris", totH, CERT_HARRIS], ["Trump", totT, CERT_TRUMP]]) {
  const err = Math.abs(got - cert) / cert;
  if (err > 0.01) throw new Error(`${label} total off by ${(100 * err).toFixed(2)}% — refusing to seed`);
}
const natMargin = ((totH - totT) / (totH + totT)) * 100;
console.log(`reconciled; national two-way margin ${natMargin.toFixed(2)} across ${states.size} states`);

// Old leans for the diff report.
const races = [];
for (const type of ["senate", "governor"]) {
  races.push(...(await (await fetch(`${API}/races?type=${type}&limit=100`)).json()));
}

const out = [
  "-- Generated by scripts/build-state-leans.mjs — do not edit.",
  "-- State leans computed from The Downballot's 2024 results (with",
  "-- attribution), reconciled against certified totals; replaces the",
  "-- original hand-written seed estimates.",
  "",
];
console.log("\nstate  old(seed)  computed   diff");
const diffs = [];
for (const r of races.sort((a, b) => a.race_id.localeCompare(b.race_id))) {
  const s = states.get(r.state);
  if (!s) continue;
  const lean = ((s.harris - s.trump) / (s.harris + s.trump)) * 100 - natMargin;
  out.push(`UPDATE races SET partisan_lean = ${lean.toFixed(1)} WHERE id = '${r.race_id}';`);
  const old = r.partisan_lean ?? 0;
  const diff = lean - old;
  diffs.push({ id: r.race_id, old, lean, diff });
  if (Math.abs(diff) >= 3) {
    console.log(
      `${r.race_id.padEnd(22)} ${String(old).padStart(6)}  ${lean.toFixed(1).padStart(8)}  ${(diff >= 0 ? "+" : "") + diff.toFixed(1)}`,
    );
  }
}
const mad = diffs.reduce((a, d) => a + Math.abs(d.diff), 0) / diffs.length;
console.log(`\nmean |hand-written error| = ${mad.toFixed(1)} pts across ${diffs.length} races`);
writeFileSync("data/seed-state-leans.sql", out.join("\n") + "\n");
console.log(`wrote data/seed-state-leans.sql (${diffs.length} updates)`);
